// Gregorian calendar and Western digits in Arabic, to match the rest of the numbers on screen
const LOCALES = { en: 'en-US', ar: 'ar-u-nu-latn-ca-gregory' }

const LanguageContext = createContext(null)

function readSavedLang() {
  try {
    return localStorage.getItem('lang') === 'ar' ? 'ar' : 'en'
  } catch {
    return 'en'
  }
}

export function LanguageProvider({ children }) {
  const [lang, setLang] = useState(readSavedLang)

  useEffect(() => {
    document.documentElement.lang = lang
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr'
    try {
      localStorage.setItem('lang', lang)
    } catch {
      // storage unavailable: the choice just won't be remembered
    }
  }, [lang])

  const toggle = () => setLang((l) => (l === 'en' ? 'ar' : 'en'))
  return <LanguageContext.Provider value={{ lang, t: STRINGS[lang], toggle, locale: LOCALES[lang] }}>{children}</LanguageContext.Provider>
}

export function useI18n() {
  return useContext(LanguageContext)
}
